#!/usr/bin/env bash
# Aggregates bench/out/*.json into metrics.json (repo root) and regenerates
# the generated section of docs/results.md. Missing inputs become null.
set -euo pipefail
# shellcheck source=bench/lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"
need jq

bench_json() { local f="${BENCH_OUT}/$1.json"; if [[ -s "$f" ]]; then cat "$f"; else echo null; fi; }
CONTROLS_DOC="${BENCH_ROOT}/docs/compliance/nis2-dora-map.md"
controls=$(grep -oE '^\| C[0-9]+ \|' "$CONTROLS_DOC" 2>/dev/null | sort -u | wc -l)

env_json=$(jq -n \
  --arg k8s "$(k version -o json 2>/dev/null | jq -r .serverVersion.gitVersion)" \
  --argjson nodes "$(k get nodes --no-headers 2>/dev/null | wc -l)" \
  --arg kernel "$(uname -r)" --argjson cpus "$(nproc)" \
  --arg mem "$(awk '/MemTotal/ {printf "%.1f GiB", $2/1048576}' /proc/meminfo)" \
  --arg commit "$(git -C "${BENCH_ROOT}" rev-parse --short HEAD)" \
  '{kubernetes: $k8s, nodes: $nodes, host_kernel: $kernel, host_cpus: $cpus, host_memory: $mem, git_commit: $commit}')

jq -n \
  --argjson env "$env_json" \
  --argjson reg "$(bench_json regressions)" --argjson clean "$(bench_json clean-releases)" \
  --argjson adm "$(bench_json admission-k6)" --argjson att "$(bench_json attacks)" --argjson rot "$(bench_json svid-rotation)" \
  --argjson controls "${controls:-0}" '
  def ratio(a; b): if a == null or b == null or b == 0 then null else ((a / b) * 1000 | round / 1000) end;
  {
    generated_at: (now | todate),
    environment: $env,
    idp_tp:       ratio($reg.summary.detected; $reg.summary.total),
    idp_false_rb: ratio($clean.summary.false_rollbacks; $clean.summary.total),
    idp_clean:    ratio($clean.summary.promoted; $clean.summary.total),
    idp_detect:   $reg.summary.median_detect_s,
    idp_lead:     $clean.summary.p50_lead_s,
    zt_adm_p99:   (if $adm then ($adm.latency_ms.p99 * 10 | round / 10) else null end),
    zt_attacks:   ratio($att.summary.blocked; $att.summary.attacks),
    zt_rot:       (if $rot then $rot.summary.handshake_failures else null end),
    zt_controls:  $controls,
    units: {
      idp_tp: "bad releases aborted / bad releases shipped",
      idp_false_rb: "clean releases aborted / clean releases shipped",
      idp_clean: "clean releases promoted / clean releases shipped",
      idp_detect: "seconds, median, canary start to abort",
      idp_lead: "seconds, p50, git commit to full promotion",
      zt_adm_p99: "milliseconds, p99 pod admission latency (dry-run) under k6 load",
      zt_attacks: "attacks rejected / attacks replayed",
      zt_rot: "failed mTLS handshakes across SVID rotations (target 0)",
      zt_controls: "controls mapped in docs/compliance/nis2-dora-map.md"
    },
    context: {
      regressions: (if $reg then {total: $reg.summary.total} else null end),
      clean_releases: (if $clean then {total: $clean.summary.total} else null end),
      admission: (if $adm then {vus: $adm.vus, think_s: $adm.think_s, requests: $adm.requests, rps: $adm.rps, failed: $adm.failed, p50_ms: $adm.latency_ms.p50, p95_ms: $adm.latency_ms.p95, kyverno_replicas: ($adm.kyverno_admission_replicas | length)} else null end),
      attacks: (if $att then {baseline_admitted: $att.summary.baseline_admitted} else null end),
      svid_rotation: (if $rot then {svid_ttl: $rot.svid_ttl, duration: $rot.duration, requests: $rot.summary.requests, client_rotations: $rot.summary.client_rotations, server_rotations: $rot.summary.server_rotations} else null end)
    }
  }' > "${BENCH_ROOT}/metrics.json"

# ---- docs/results.md generated section
f1() { awk -v v="$1" 'BEGIN { if (v == "" || v == "null") print "n/a"; else printf "%.1f", v }'; }
gen=$(mktemp)
{
  m="${BENCH_ROOT}/metrics.json"
  echo "_Generated by \`bench/render.sh\` on $(jq -r .generated_at "$m") from commit \`$(jq -r .environment.git_commit "$m")\`; Kubernetes $(jq -r .environment.kubernetes "$m"), $(jq -r .environment.nodes "$m") nodes, host $(jq -r '"\(.environment.host_cpus) CPUs / \(.environment.host_memory)"' "$m")._"
  echo
  echo "| Metric | Value | Meaning |"
  echo "|---|---|---|"
  jq -r '. as $m | ["idp_tp","idp_false_rb","idp_clean","idp_detect","idp_lead","zt_adm_p99","zt_attacks","zt_rot","zt_controls"][]
         | "| `\(.)` | \($m[.] // "n/a") | \($m.units[.]) |"' "$m"
  if [[ -s "${BENCH_OUT}/regressions.json" ]]; then
    echo; echo "### Bad releases"; echo
    echo "| Case | Fault | Outcome | Canary start to abort | Failed analysis metrics |"
    echo "|---|---|---|---|---|"
    jq -r '.cases[] | "| \(.case) | `\(.fault)` | \(.outcome) | \(.canary_to_end_s // "n/a") s | \([.analysis[] | select(.phase == "Failed") | .metric] | unique | join(", ") | if . == "" then "-" else . end) |"' "${BENCH_OUT}/regressions.json"
  fi
  if [[ -s "${BENCH_OUT}/clean-releases.json" ]]; then
    echo; echo "### Clean releases"; echo
    echo "| Release | Outcome | Canary start to promotion | Commit to promotion |"
    echo "|---|---|---|---|"
    jq -r '.releases[] | "| \(.release) | \(.outcome) | \(.canary_to_end_s // "n/a") s | \(.lead_s // "n/a") s |"' "${BENCH_OUT}/clean-releases.json"
  fi
  if [[ -s "${BENCH_OUT}/attacks.json" ]]; then
    echo; echo "### Attack replay"; echo
    echo "| Attempt | Expected | Result | Verdict | Rejected by |"
    echo "|---|---|---|---|---|"
    jq -r '.results[] | "| \(.attack) | \(.expected) | \(.result) | \(.verdict) | \(if .result == "denied" then (.message | if test("ValidatingAdmissionPolicy") then "ValidatingAdmissionPolicy platform-idp-pod-security" elif test("verify-signature") then "Kyverno verify-supply-chain/verify-signature" elif test("allowed-registry") then "Kyverno restrict-registries" else "other" end) else "-" end) |"' "${BENCH_OUT}/attacks.json"
  fi
  if [[ -s "${BENCH_OUT}/admission-k6.json" ]]; then
    a="${BENCH_OUT}/admission-k6.json"
    echo; echo "### Admission latency"; echo
    echo "| VUs | Think time | Requests | Throughput | Failed | p50 | p95 | p99 | max |"
    echo "|---|---|---|---|---|---|---|---|---|"
    echo "| $(jq -r .vus "$a") | $(jq -r .think_s "$a") s | $(jq -r .requests "$a") | $(jq -r .rps "$a") req/s | $(jq -r .failed "$a") | $(f1 "$(jq -r .latency_ms.p50 "$a")") ms | $(f1 "$(jq -r .latency_ms.p95 "$a")") ms | $(f1 "$(jq -r .latency_ms.p99 "$a")") ms | $(f1 "$(jq -r .latency_ms.max "$a")") ms |"
  fi
  if compgen -G "${BENCH_OUT}/admission-k6-vus*.json" >/dev/null; then
    echo; echo "Load sweep (same test, one run per VU level):"; echo
    mapfile -t sweep < <(for f in "${BENCH_OUT}"/admission-k6-vus*.json; do printf '%s\t%s\n' "$(jq -r .vus "$f")" "$f"; done | sort -n | cut -f2)
    echo "| VUs | Throughput | Failed | p50 | p95 | p99 | p99 < $(jq -r .threshold_p99_ms "${sweep[0]}") ms |"
    echo "|---|---|---|---|---|---|---|"
    for f in "${sweep[@]}"; do
      echo "| $(jq -r .vus "$f") | $(jq -r .rps "$f") req/s | $(jq -r .failed "$f") | $(f1 "$(jq -r .latency_ms.p50 "$f")") ms | $(f1 "$(jq -r .latency_ms.p95 "$f")") ms | $(f1 "$(jq -r .latency_ms.p99 "$f")") ms | $(jq -r 'if .latency_ms.p99 < .threshold_p99_ms then "yes" else "no" end' "$f") |"
    done
  fi
  if [[ -s "${BENCH_OUT}/svid-rotation.json" ]]; then
    r="${BENCH_OUT}/svid-rotation.json"
    echo; echo "### SVID rotation"; echo
    echo "| SVID TTL (test only) | Duration | Requests | Failed handshakes | Other errors | Client rotations | Server SVIDs seen |"
    echo "|---|---|---|---|---|---|---|"
    jq -r '"| \(.svid_ttl) | \(.duration) | \(.client.requests) | \(.client.handshake_failures) | \(.client.http_errors + .client.other_errors) | \(.client.client_rotations) | \(.client.distinct_server_svids) (\(.server_pods) pods) |"' "$r"
  fi
} > "$gen"

doc="${BENCH_ROOT}/docs/results.md"
if [[ -f "$doc" ]] && grep -q '<!-- results:begin -->' "$doc"; then
  awk -v gen="$gen" '
    /<!-- results:begin -->/ { print; while ((getline l < gen) > 0) print l; skip = 1; next }
    /<!-- results:end -->/   { skip = 0 }
    !skip' "$doc" > "${doc}.tmp" && mv "${doc}.tmp" "$doc"
else
  warn "docs/results.md has no results markers; generated section printed below"
  cat "$gen"
fi
rm -f "$gen"
log "wrote metrics.json and docs/results.md"
